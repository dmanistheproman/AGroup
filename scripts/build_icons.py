"""Build frontend/assets/icons/lucide.svg from Lucide icons (https://lucide.dev, ISC licence).

Add an icon: put its Lucide name in ICONS, then run from the project root:

    python scripts/build_icons.py

Use it in a page:   <svg class="icon"><use href="assets/icons/lucide.svg#heart"></use></svg>
or from JS:         AGroupIcons.icon('heart')
"""
import re
import sys
import urllib.request
from pathlib import Path

VERSION = "1.61.0"   # pinned lucide-static version
CDN = f"https://cdn.jsdelivr.net/npm/lucide-static@{VERSION}"

ICONS = sorted({
    # arrows
    "arrow-up-right", "arrow-right", "arrow-left", "arrow-left-right", "arrow-down", "rotate-ccw",
    # account
    "log-in", "log-out", "user", "bell", "inbox", "layout-dashboard", "life-buoy", "x", "check-check",
    # portal navigation
    "layout-grid", "badge-check", "list", "history", "chart-column", "check", "flag",
    "upload", "download", "house", "ellipsis", "banknote", "receipt", "file-text", "merge",
    # customer site
    "heart", "star",
})

OUT_DIR = Path(__file__).resolve().parent.parent / "frontend" / "assets" / "icons"


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode("utf-8")


def symbol(name, svg):
    """Turn one Lucide SVG file into a <symbol> (shape only)."""
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()
    inner = re.sub(r"\s*\n\s*", "", inner)
    # Only the shape: fill/stroke come from css/icons.css, so an icon can be shown filled.
    return f'<symbol id="{name}" viewBox="0 0 24 24">{inner}</symbol>'


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    symbols, missing = [], []
    for name in ICONS:
        try:
            symbols.append(symbol(name, fetch(f"{CDN}/icons/{name}.svg")))
        except Exception as exc:  # report every missing icon, not just the first
            missing.append(f"{name} ({exc})")
    if missing:
        sys.exit("Not found in lucide-static " + VERSION + ": " + ", ".join(missing))

    sprite = (f"<!-- Lucide icons v{VERSION} (ISC licence, see LICENSE). "
              f"Generated by scripts/build_icons.py; do not edit by hand. -->\n"
              '<svg xmlns="http://www.w3.org/2000/svg">\n'
              + "\n".join(symbols) + "\n</svg>\n")
    (OUT_DIR / "lucide.svg").write_text(sprite, encoding="utf-8")
    (OUT_DIR / "LICENSE").write_text(fetch(f"{CDN}/LICENSE"), encoding="utf-8")
    print(f"Wrote {len(symbols)} icons to {OUT_DIR / 'lucide.svg'}")


if __name__ == "__main__":
    main()
